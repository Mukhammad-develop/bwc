// Mouse move effect for buttons and cards
document.querySelectorAll('.btn-primary,.submit-btn,.feature-card').forEach(el => {
    el.addEventListener('mousemove', e => {
        const r = el.getBoundingClientRect();
        el.style.setProperty('--mouse-x', `${((e.clientX - r.left) / r.width) * 100}%`);
        el.style.setProperty('--mouse-y', `${((e.clientY - r.top) / r.height) * 100}%`);
    });
});

// Smooth scroll for anchor links
document.querySelectorAll('a[href^="#"]').forEach(a => {
    a.addEventListener('click', function(e) {
        e.preventDefault();
        const t = document.querySelector(this.getAttribute('href'));
        if (t) window.scrollTo({
            top: t.getBoundingClientRect().top + window.pageYOffset - nav.offsetHeight,
            behavior: 'smooth'
        });
    });
});

