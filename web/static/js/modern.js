let currentLang = 'en';

// Auto-detect language on load (with localStorage persistence)
(function() {
    const supportedLangs = Object.keys(T);
    
    // Check if user previously selected a language
    const savedLang = localStorage.getItem('brightway_lang');
    if (savedLang && supportedLangs.includes(savedLang)) {
        currentLang = savedLang;
    } else {
        // Auto-detect from browser
        const browserLangs = (navigator.languages || [navigator.language || '']).map(x => x.toLowerCase());
        
        for (const lang of browserLangs) {
            const code = lang.split('-')[0]; // en-US -> en, ru-RU -> ru
            if (supportedLangs.includes(code)) {
                currentLang = code;
                break;
            }
        }
    }
    
    setLanguage(currentLang);
})();

function setLanguage(lang) {
    currentLang = lang;
    const translations = T[lang];
    if (!translations) return;
    
    // Save to localStorage for persistence across pages
    localStorage.setItem('brightway_lang', lang);

    // Translate document title by current page
    const path = window.location.pathname;
    if (path.includes('/services')) {
        document.title = translations.titleServices || document.title;
    } else if (path.includes('/contact')) {
        document.title = translations.titleContact || document.title;
    } else {
        document.title = translations.titleHome || document.title;
    }
    
    // Update all translated elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[key]) {
            el.innerHTML = translations[key];
        }
    });
    
    // Update language label
    const langLabel = document.getElementById('currentLangLabel');
    if (langLabel) {
        langLabel.textContent = lang.toUpperCase();
    }
    
    // Update active state
    document.querySelectorAll('.lang-option').forEach(option => {
        option.classList.toggle('active', option.getAttribute('data-lang') === lang);
    });
    
    // Close dropdown
    const dropdown = document.getElementById('langDropdown');
    if (dropdown) {
        dropdown.classList.remove('open');
    }
}

